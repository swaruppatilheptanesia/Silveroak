// Helper functions
export const getOffersByStudent = (studentId: string): Offer[] => {
  return mockOffers.filter(o => o.student_id === studentId);
};

export const getOffersByCompany = (companyId: string): Offer[] => {
  return mockOffers.filter(o => o.company_id === companyId);
};

export const getOffersByPosting = (postingId: string): Offer[] => {
  return mockOffers.filter(o => o.posting_id === postingId);
};

export const getOfferAudit = (offerId: string): OfferAuditEntry[] => {
  return mockOfferAudit.filter(a => a.offer_id === offerId);
};

export const getActiveOffer = (studentId: string): Offer | undefined => {
  return mockOffers.find(o => o.student_id === studentId && o.status === 'accepted' && o.joining_status !== 'did_not_join');
};

export const isStudentBlocked = (studentId: string): boolean => {
  return mockOffers.some(o => o.student_id === studentId && o.applications_blocked);
};

export const getOfferStats = () => {
  return {
    total: mockOffers.length,
    pending: mockOffers.filter(o => o.status === 'pending_student_action').length,
    accepted: mockOffers.filter(o => o.status === 'accepted').length,
    rejectedByAdmin: mockOffers.filter(o => o.status === 'rejected_by_admin').length,
    joined: mockOffers.filter(o => o.joining_status === 'joined').length,
    dnj: mockOffers.filter(o => o.joining_status === 'did_not_join').length,
    blocked: mockOffers.filter(o => o.applications_blocked).length,
  };
};
