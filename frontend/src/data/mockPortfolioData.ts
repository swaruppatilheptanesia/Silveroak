// Helper functions
export const getPortfolioByStudent = (studentId: string) =>
  mockPortfolios.find(p => p.student_id === studentId);

export const getPortfolioProjects = (portfolioId: string) =>
  mockPortfolioProjects.filter(p => p.portfolio_id === portfolioId);

export const getInternshipShowcases = (portfolioId: string) =>
  mockInternshipShowcases.filter(s => s.portfolio_id === portfolioId);

export const getPortfolioStats = () => ({
  total: mockPortfolios.length,
  published: mockPortfolios.filter(p => p.status === 'published').length,
  draft: mockPortfolios.filter(p => p.status === 'draft').length,
  withProjects: mockPortfolios.filter(p => p.project_count > 0).length,
  withInternships: mockPortfolios.filter(p => p.internship_count > 0).length,
  avgProjects: Math.round((mockPortfolios.reduce((s, p) => s + p.project_count, 0) / mockPortfolios.length) * 10) / 10,
});
