// Helper Functions
export const getApplicationsByPosting = (postingId: string): Application[] => {
  return mockApplications.filter(app => app.posting_id === postingId);
};

export const getApplicationsByStudent = (studentId: string): Application[] => {
  return mockApplications.filter(app => app.student_id === studentId);
};

export const getApplicationsByStage = (stage: ApplicationStage): Application[] => {
  return mockApplications.filter(app => app.current_stage === stage);
};

export const getApplicationById = (id: string): Application | undefined => {
  return mockApplications.find(app => app.id === id);
};

export const getStageHistoryByApplication = (applicationId: string): ApplicationStageHistory[] => {
  return mockStageHistory.filter(h => h.application_id === applicationId);
};

export const getFeedbackByApplication = (applicationId: string): RecruiterFeedback[] => {
  return mockRecruiterFeedback.filter(f => f.application_id === applicationId);
};

export const getShortlistedForCompany = (companyId: string): Application[] => {
  return mockApplications.filter(
    app => app.company_id === companyId && 
    ['shortlisted', 'test_scheduled', 'interview', 'hr_round', 'offer_released'].includes(app.current_stage)
  );
};

export const getApplicationStats = (postingId?: string) => {
  const apps = postingId 
    ? mockApplications.filter(a => a.posting_id === postingId)
    : mockApplications;
  
  return {
    total: apps.length,
    applied: apps.filter(a => a.current_stage === 'applied').length,
    mockRound: apps.filter(a => a.current_stage === 'mock_round').length,
    shortlisted: apps.filter(a => a.current_stage === 'shortlisted').length,
    testScheduled: apps.filter(a => a.current_stage === 'test_scheduled').length,
    interview: apps.filter(a => a.current_stage === 'interview').length,
    hrRound: apps.filter(a => a.current_stage === 'hr_round').length,
    offerReleased: apps.filter(a => a.current_stage === 'offer_released').length,
    rejected: apps.filter(a => a.current_stage === 'rejected').length,
    mockPassed: apps.filter(a => a.mock_round_result === 'passed').length,
    mockFailed: apps.filter(a => a.mock_round_result === 'failed').length,
  };
};
